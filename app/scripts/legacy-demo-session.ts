function setCookie(raw: string, index: number): ReceivedCookie {
  const [pairPart, ...attrs] = raw.split(";");
  const [name, ...valueParts] = pairPart.split("=");
  return {
    index,
    name: name.trim(),
    value: valueParts.join("=").trim(),
    attributes: attrs.map((a) => {
      const [k, ...v] = a.trim().split("=");
      return { name: k.trim(), value: v.length ? v.join("=").trim() : undefined };
    }),
    raw,
  };
}

