const pair =
  (name: string, value: string, note?: string) =>
  (index: number): HeaderPair => ({
    index,
    name,
    value,
    kind: name.startsWith(":") ? "pseudo" : "regular",
    note,
  });

function headers(rows: [string, string, string?][]): HeaderPair[] {
  return rows.map(([name, value, note], index) => pair(name, value, note)(index));
}

let evCounter = 0;
function ev(
  source: EvidenceRef["source"],
  event: string,
  timestamp: string,
  method: string,
  eventRef?: string,
): EvidenceRef {
  evCounter += 1;
  return { source, event, timestamp, method, eventRef: eventRef ?? `ev-${evCounter}` };
}

