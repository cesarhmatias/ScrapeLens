def jslen(value: str) -> int:
    """Natural for Ajax lengths are JavaScript string lengths (UTF-16 units)."""
    return len(value.encode("utf-16-le", "surrogatepass")) // 2


def serialize(sid: str, pid: str, model: str, page: str, event: str,
              props: dict[str, str], delta: str, init: bool = False,
              init_param: str = "") -> str:
    """Request-side stream: i/v + widths + parts, then p-groups, then x+delta."""
    parts = [sid, pid, "", model, "dummy", page, event, "false"]
    widths = [2, 2, 2, 2, 2, 3, 5, 1]
    out = ("i" if init else "v") + "".join(
        str(jslen(v)).zfill(w) for v, w in zip(parts, widths)
    ) + "".join(parts)
    for name, value in props.items():
        value = str(value)
        out += "p" + str(jslen(name)).zfill(2) + str(jslen(value)).zfill(5) + name + value
    return out + "x" + str(jslen(delta)).zfill(2) + delta


def response_stream(fields: list[tuple[str, str]], delta: str) -> str:
    """Response-side stream exercising the documented opcodes.

    l = clear, p = literal (2+5), s = name definition, q/w = dictionary
    reference (q: 2+5, w: 2+10), b/c = scope, z = literal in scope (2+10),
    k = removal, x = delta. Lengths are UTF-16 code units.
    """
    rows = [(k, v) for k, v in fields if "items[" in k]
    simple = [(k, v) for k, v in fields if "items[" not in k]

    out = ["l"]
    for k, v in simple:
        out.append("p" + str(jslen(k)).zfill(2) + str(jslen(v)).zfill(5) + k + v)

    if rows:
        # Row 0 travels through the name dictionary (s + q), as repeated table
        # columns do in the real responses.
        key0, val0 = rows[0]
        out.append("s" + str(jslen("A")).zfill(1) + str(jslen(key0)).zfill(2) + "A" + key0)
        out.append("q" + str(jslen("A")).zfill(2) + str(jslen(val0)).zfill(5) + "A" + val0)
        if len(rows) > 1:
            # Row 1 through the same dictionary, with a 10-digit length (w),
            # inside the situacao_rows scope.
            key1, val1 = rows[1]
            local = key1.split(".", 1)[1]
            out.append("s" + str(jslen("B")).zfill(1) + str(jslen("situacao_rows." + local)).zfill(2) + "B" + "situacao_rows." + local)
            out.append("b" + str(jslen("situacao_rows")).zfill(2) + "situacao_rows")
            out.append("z" + str(jslen(local)).zfill(2) + str(jslen(val1)).zfill(10) + local + val1)
            out.append("c")
    out.append("k" + str(jslen("v_tmp")).zfill(2) + "v_tmp")
    out.append("x" + str(jslen(delta)).zfill(2) + delta)
    return "".join(out)


def form_body(fields: dict[str, str] | list[tuple[str, str]]) -> str:
    pairs = fields.items() if isinstance(fields, dict) else fields
    return "&".join(
        f"{urllib.parse.quote(k, safe='')}={urllib.parse.quote(str(v), safe='')}"
        for k, v in pairs
    )


def cookie_header(mode: str) -> str | None:
    """none: first request (jar empty); js: only JSESSIONID (set by step 0); both: + TS* set by /TSPD/."""
    return {"none": None, "js": JSESSION, "both": COOKIE_REQUEST}[mode]


def request_headers(kind: str, referer: str | None = None, cookie_mode: str = "both") -> list[dict[str, str]]:
    if kind == "xhr":
        headers = [(n, v) for n, v in HEADERS_XHR]
        if referer:
            headers = [(n, referer if n == "referer" else v) for n, v in headers]
        if cookie_header(cookie_mode):
            headers.append(("cookie", cookie_header(cookie_mode)))
        headers.append(("content-length", "0"))  # replaced per request
        headers.append(("connection", "keep-alive"))
    else:
        headers = list(HEADERS_COMMON)
        if cookie_header(cookie_mode):
            headers.append(("cookie", cookie_header(cookie_mode)))
        headers.append(("sec-fetch-dest", "document"))
        headers.append(("sec-fetch-mode", "navigate"))
        headers.append(("sec-fetch-site", "same-origin" if kind != "entry" else "none"))
        headers.append(("upgrade-insecure-requests", "1"))
    return [{"name": n, "value": v} for n, v in headers]


