#!/usr/bin/env python3
"""Turns results.json of a run into RESULTS.md (repository-safe: no local paths, no secrets).

Usage: python3 summarize.py <run-folder>/results.json > RESULTS.md
"""
import json
import pathlib
import re
import sys

LABEL = {"passou": "passou", "falhou": "falhou", "nao_executado": "não executado"}


def scrub(text: str) -> str:
    # local folders never go into the repository; keep only the leaf name
    text = re.sub(r"/(Users|private|var|tmp)/\S+", "<local path>", text)
    return text.replace("|", "\\|")


def main() -> int:
    rows = json.loads(pathlib.Path(sys.argv[1]).read_text())
    print("# Proxy acceptance: results (v0.1.2)\n")
    print("Generated by `summarize.py` from a run of `run_acceptance.py`. Synthetic data only; "
          "local test proxies; not verified against commercial providers.\n")
    counts = {}
    for row in rows:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    print("Totals: " + ", ".join(f"{LABEL[k]} {v}" for k, v in sorted(counts.items())) + ".\n")
    current = None
    for row in rows:
        if row["section"] != current:
            current = row["section"]
            print(f"\n## {current}\n")
            print("| Criterion | Case | Result | Detail |")
            print("|---|---|---|---|")
        print(f"| {scrub(row['criterion'])} | {scrub(row['case'])} | {LABEL[row['status']]} | {scrub(row['detail'])} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
